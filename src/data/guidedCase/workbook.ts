import type { GuidedCaseRequirement } from './types'
import {
  guidedCaseTitle,
  guidedCaseBrief,
  guidedCaseScope,
  guidedCaseActors,
  guidedCaseOpenQuestions,
} from './overview'
import { guidedCaseSources } from './sources'
import {
  guidedCaseFunctionalRequirements,
  guidedCaseNonFunctionalRequirements,
} from './requirements'
import {
  guidedCaseCandidateInventory,
  guidedCaseRelations,
  guidedCaseMermaid,
  guidedCaseSql,
} from './model'

const sourcesMarkdown = guidedCaseSources.map((source) => [
  `## ${source.title}`,
  `**Tipo:** ${source.type}`,
  '',
  source.summary,
  '',
  ...source.evidence.map((item) => `- ${item}`),
  '',
].join('\n')).join('\n')

const requirementsMarkdown = (title: string, requirements: GuidedCaseRequirement[]) => [
  `# ${title}`,
  '',
  '| ID | Prioridad | Requisito | Fuente | Criterio de aceptación |',
  '|---|---|---|---|---|',
  ...requirements.map((item) => `| ${item.id} | ${item.priority} | ${item.text} | ${item.source} | ${item.acceptance} |`),
  '',
].join('\n')

export function buildGuidedCaseWorkbookMarkdown() {
  return [
    `# Caso guiado · ${guidedCaseTitle}`,
    '',
    'Este cuaderno contiene la base documental y la solución esperada para practicar el análisis de requisitos hasta el modelo entidad-relación. Los datos son ficticios.',
    '',
    '## Cómo usarlo',
    '1. Lee el contexto y las fuentes en el orden en que fueron levantadas.',
    '2. Responde cada pregunta del ejercicio antes de consultar el resultado esperado.',
    '3. Conserva tus decisiones, supuestos y preguntas abiertas; un modelo defendible deja trazabilidad.',
    '4. Compara tu MER con el modelo esperado. Se aceptan variantes si están justificadas por los requisitos.',
    '',
    '## Contexto',
    guidedCaseBrief,
    '',
    '## Alcance incluido',
    ...guidedCaseScope.in.map((item) => `- ${item}`),
    '',
    '## Fuera de alcance',
    ...guidedCaseScope.out.map((item) => `- ${item}`),
    '',
    '## Actores',
    ...guidedCaseActors.map((actor) => `- **${actor.name}:** ${actor.action}`),
    '',
    '# Fuentes levantadas',
    '',
    sourcesMarkdown,
    requirementsMarkdown('Requisitos funcionales consolidados', guidedCaseFunctionalRequirements),
    requirementsMarkdown('Requisitos no funcionales consolidados', guidedCaseNonFunctionalRequirements),
    '# Reglas y preguntas abiertas',
    '',
    '## Preguntas que no se deben resolver por intuición',
    ...guidedCaseOpenQuestions.map((item) => `- [ ] ${item}`),
    '',
    '# Inventario de conceptos',
    '',
    '| Concepto | Decisión | Razón |',
    '|---|---|---|',
    ...guidedCaseCandidateInventory.map((item) => `| ${item.word} | ${item.decision} | ${item.reason} |`),
    '',
    '# Relaciones y cardinalidades esperadas',
    '',
    '| Par | Verbo | Cardinalidad | Mínimo/máximo | Regla |',
    '|---|---|---|---|---|',
    ...guidedCaseRelations.map((item) => `| ${item.pair} | ${item.verb} | ${item.cardinality} | ${item.left} / ${item.right} | ${item.rule} |`),
    '',
    '# Resultado esperado',
    '',
    'El análisis debe concluir que las entidades regulares son CLIENTE, VEHICULO, ORDEN_SERVICIO, SERVICIO, TECNICO, REPUESTO y PAGO. Las entidades asociativas DETALLE_SERVICIO, ASIGNACION_TECNICO y CONSUMO_REPUESTO resuelven las relaciones N:M y almacenan los atributos propios de cada hecho.',
    '',
    'Decisiones importantes: usar identificadores técnicos; proteger documento, placa y códigos con UNIQUE; congelar tarifa_aplicada y precio_aplicado en los hechos; no persistir total como fuente primaria; usar RESTRICT para conservar la historia; permitir que una orden nazca sin pago y, según la validación final, sin técnico asignado.',
    '',
    '## MER esperado',
    '```mermaid',
    guidedCaseMermaid,
    '```',
    '',
    '## DDL orientativo',
    '```sql',
    guidedCaseSql,
    '```',
    '',
  ].join('\n')
}

